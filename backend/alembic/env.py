def include_object(object, name, type_, reflected, compare_to):
    """Keep autogenerated migrations away from PostGIS-internal objects."""
    if type_ == "table":
        if getattr(object, "schema", None) in EXCLUDED_SCHEMAS:
            return False
        if name in EXCLUDED_TABLES:
            return False

    if type_ == "index" and getattr(object, "table", None) is not None:
        table = object.table
        if getattr(table, "schema", None) in EXCLUDED_SCHEMAS:
            return False
        if table.name in EXCLUDED_TABLES:
            return False

    return True


def include_name(name, type_, parent_names):
    """Name-level filter: skip PostGIS-internal schemas and tables.

    alembic 1.19 may flatten non-default schemas (schema_name=None), so the
    table-name check is the reliable guard."""
    if type_ == "schema":
        return name not in EXCLUDED_SCHEMAS
    if type_ == "table":
        return name not in EXCLUDED_TABLES
    return True


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode — generates SQL without connecting."""
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        include_object=include_object,
        include_name=include_name,
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        include_object=include_object,
        include_name=include_name,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    async with connectable.connect() as connection:
        # Ensure PostGIS and pgvector exist BEFORE any migration runs
        # (idempotent — covers fresh and pre-existing databases).
        await connection.execute(text("CREATE EXTENSION IF NOT EXISTS postgis"))
        await connection.execute(text("CREATE EXTENSION IF NOT EXISTS vector"))
        await connection.commit()

        await connection.run_sync(do_run_migrations)

    await connectable.dispose()


def run_migrations_online() -> None:
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
