"""
Alembic Migration Environment (async SQLAlchemy)

Run via the `migrate` compose service:  alembic upgrade heads

- The database URL comes from app settings (`alembic.ini` leaves it empty).
- PostGIS + pgvector are ensured before any migration runs.
- Installed modules' models & migration dirs are discovered from
  `modules.lock.yaml` so `upgrade head` covers module tables too.
- PostGIS-internal objects are excluded so autogenerated migrations never
  try to drop/alter them.
"""
