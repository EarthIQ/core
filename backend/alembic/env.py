# ── PostGIS / pgvector internals Alembic must never touch ─────────────────────
# PostGIS installs a fixed set of internal tables in its own schemas (tiger,
# tiger_data, topology). alembic 1.19 + SQLAlchemy 2.x can reflect them with
# schema=None (flattened), so we filter by name in addition to schema.
